$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$directory = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$catalogue = Get-Content -LiteralPath (Join-Path $directory 'tests/scanner/words.json') -Raw | ConvertFrom-Json
$nodes = [Collections.Generic.List[object]]::new()
$statementStarts = [Collections.Generic.List[int]]::new()
$nodes.Add(@{ edges = [Collections.Generic.SortedDictionary[int,int]]::new(); role = 0 })
foreach ($word in $catalogue.words) {
    $state = 0
    foreach ($character in $word.word.ToCharArray()) {
        $scalar = [int]$character
        if (-not $nodes[$state].edges.ContainsKey($scalar)) {
            $nodes[$state].edges.Add($scalar, $nodes.Count)
            $nodes.Add(@{ edges = [Collections.Generic.SortedDictionary[int,int]]::new(); role = 0 })
        }
        $state = $nodes[$state].edges[$scalar]
    }
    $role = if ($word.role -ceq 'reserved') { 1 } else { 2 }
    if ($word.ordinaryCallEligible) { $role += 4 }
    $nodes[$state].role = $role
    if ($word.word -ceq 'then' -or $word.word -ceq 'else') { $statementStarts.Add($state) }
}
$text = [Text.StringBuilder]::new()
[void]$text.AppendLine('UBE SOURCE 1 MODULE')
[void]$text.AppendLine('Attribute UBE_Name = "ScannerWords"')
[void]$text.AppendLine('')
[void]$text.AppendLine("' Generated by tools/generate-scanner-words.ps1 from tests/scanner/words.json.")
[void]$text.AppendLine("' Immutable numeric trie: one folded scalar step per original name scalar.")
[void]$text.AppendLine("' State zero is the root; -1 is a permanent miss. No source storage or allocation.")
[void]$text.AppendLine('Function ScannerWordStep(ByVal State As Long, ByVal Scalar As Long) As Long')
[void]$text.AppendLine('    ScannerWordStep = -1')
[void]$text.AppendLine('    If State < 0 Then')
[void]$text.AppendLine('        Exit Function')
[void]$text.AppendLine('    End If')
function Add-StateTree([int[]]$States,[int]$Start,[int]$Count,[string]$Indent,[bool]$Roles) {
    if ($Count -gt 1) {
        $left = [int][Math]::Floor($Count / 2)
        [void]$text.AppendLine($Indent + 'If State <= ' + $States[$Start + $left - 1] + ' Then')
        Add-StateTree $States $Start $left ($Indent + '    ') $Roles
        [void]$text.AppendLine($Indent + 'Else')
        Add-StateTree $States ($Start + $left) ($Count - $left) ($Indent + '    ') $Roles
        [void]$text.AppendLine($Indent + 'End If')
        return
    }
    $state = $States[$Start]
    [void]$text.AppendLine($Indent + "If State = $state Then")
    if ($Roles) {
        [void]$text.AppendLine($Indent + "    ScannerWordRole = $($nodes[$state].role)")
    } else {
        foreach ($edge in $nodes[$state].edges.GetEnumerator()) {
            [void]$text.AppendLine($Indent + "    If Scalar = $($edge.Key) Then")
            [void]$text.AppendLine($Indent + "        ScannerWordStep = $($edge.Value)")
            [void]$text.AppendLine($Indent + '        Exit Function')
            [void]$text.AppendLine($Indent + '    End If')
        }
    }
    [void]$text.AppendLine($Indent + 'End If')
}
$states = @(for ($index = 0; $index -lt $nodes.Count; $index++) { if ($nodes[$index].edges.Count -gt 0) { $index } })
Add-StateTree $states 0 $states.Count '    ' $false
[void]$text.AppendLine('End Function')
[void]$text.AppendLine('')
[void]$text.AppendLine("' Role flags: 1 reserved, 2 contextual, plus 4 for ordinary-call eligibility.")
[void]$text.AppendLine('Function ScannerWordRole(ByVal State As Long) As Long')
[void]$text.AppendLine('    ScannerWordRole = 0')
$states = @(for ($index = 0; $index -lt $nodes.Count; $index++) { if ($nodes[$index].role -gt 0) { $index } })
Add-StateTree $states 0 $states.Count '    ' $true
[void]$text.AppendLine('End Function')
[void]$text.AppendLine('')
[void]$text.AppendLine("' These grammar words open a statement when not consumed as member names.")
[void]$text.AppendLine('Function ScannerWordStartsStatement(ByVal State As Long) As Boolean')
[void]$text.AppendLine('    ScannerWordStartsStatement = False')
foreach ($state in $statementStarts) {
    [void]$text.AppendLine("    If State = $state Then")
    [void]$text.AppendLine('        ScannerWordStartsStatement = True')
    [void]$text.AppendLine('    End If')
}
[void]$text.AppendLine('End Function')
[IO.File]::WriteAllText((Join-Path $directory 'ScannerWords.bas'), $text.ToString(), [Text.UTF8Encoding]::new($false))
