param(
    [string]$OutputPath = (Join-Path $PSScriptRoot '..\include\ube\unicode_case_folding.hpp')
)

$ErrorActionPreference = 'Stop'
$unicodeVersion = '18.0.0'
$dataUrl = "https://www.unicode.org/Public/$unicodeVersion/ucd/CaseFolding.txt"
$data = (Invoke-WebRequest -UseBasicParsing -Uri $dataUrl).Content
$mappings = [System.Collections.Generic.List[object]]::new()

foreach ($line in $data -split "`n") {
    # C is a common simple/full mapping; S overrides a multi-code-point full
    # mapping with the single-code-point mapping required by UBE.
    if ($line -match '^([0-9A-F]+);\s+([CS]);\s+([0-9A-F]+);') {
        $mappings.Add([pscustomobject]@{
            Source = [Convert]::ToUInt32($Matches[1], 16)
            Target = [Convert]::ToUInt32($Matches[3], 16)
        })
    }
}

$mappings = $mappings | Sort-Object Source
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by bootstrap/tools/generate-unicode-case-folding.ps1.')
$lines.Add("// Source: Unicode $unicodeVersion CaseFolding.txt (status C and S).")
$lines.Add('// Unicode data terms: https://www.unicode.org/terms_of_use.html')
$lines.Add('// Do not edit this file manually.')
$lines.Add('')
$lines.Add('#pragma once')
$lines.Add('')
$lines.Add('#include <array>')
$lines.Add('')
$lines.Add('namespace ube::unicode {')
$lines.Add('')
$lines.Add('struct CaseFoldMapping {')
$lines.Add('    char32_t source;')
$lines.Add('    char32_t target;')
$lines.Add('};')
$lines.Add('')
$lines.Add("inline constexpr std::array<CaseFoldMapping, $($mappings.Count)> simple_case_fold_mappings = {{")
foreach ($mapping in $mappings) {
    $source = [Convert]::ToString([uint32]$mapping.Source, 16).ToUpperInvariant()
    $target = [Convert]::ToString([uint32]$mapping.Target, 16).ToUpperInvariant()
    $lines.Add("    CaseFoldMapping{0x$source, 0x$target},")
}
$lines.Add('}};')
$lines.Add('')
$lines.Add('} // namespace ube::unicode')

$resolvedOutput = [System.IO.Path]::GetFullPath($OutputPath)
[System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($resolvedOutput)) | Out-Null
[System.IO.File]::WriteAllLines($resolvedOutput, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated $($mappings.Count) Unicode simple case-fold mappings in $resolvedOutput"
