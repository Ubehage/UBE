param(
    [string]$OutputPath = (Join-Path $PSScriptRoot '..\include\ube\unicode_letter_ranges.hpp')
)

$ErrorActionPreference = 'Stop'
$unicodeVersion = '18.0.0'
$dataUrl = "https://www.unicode.org/Public/$unicodeVersion/ucd/extracted/DerivedGeneralCategory.txt"
$data = (Invoke-WebRequest -UseBasicParsing -Uri $dataUrl).Content
$ranges = [System.Collections.Generic.List[object]]::new()

foreach ($line in $data -split "`n") {
    if ($line -match '^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s+;\s+L[ultmo]\b') {
        $first = [Convert]::ToUInt32($Matches[1], 16)
        $last = if ($Matches[2]) { [Convert]::ToUInt32($Matches[2], 16) } else { $first }
        $ranges.Add([pscustomobject]@{ Low = $first; High = $last })
    }
}

$ranges = $ranges | Sort-Object Low
$merged = [System.Collections.Generic.List[object]]::new()
foreach ($range in $ranges) {
    if ($merged.Count -ne 0 -and $range.Low -le $merged[$merged.Count - 1].High + 1) {
        if ($range.High -gt $merged[$merged.Count - 1].High) {
            $merged[$merged.Count - 1].High = $range.High
        }
    } else {
        $merged.Add([pscustomobject]@{ Low = $range.Low; High = $range.High })
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by bootstrap/tools/generate-unicode-letter-ranges.ps1.')
$lines.Add("// Source: Unicode $unicodeVersion DerivedGeneralCategory.txt (Lu, Ll, Lt, Lm, Lo).")
$lines.Add('// Unicode data terms: https://www.unicode.org/terms_of_use.html')
$lines.Add('// Do not edit this file manually.')
$lines.Add('')
$lines.Add('#pragma once')
$lines.Add('')
$lines.Add('#include <array>')
$lines.Add('#include <cstdint>')
$lines.Add('')
$lines.Add('namespace ube::unicode {')
$lines.Add('')
$lines.Add('struct CodePointRange {')
$lines.Add('    char32_t first;')
$lines.Add('    char32_t last;')
$lines.Add('};')
$lines.Add('')
$lines.Add("inline constexpr std::array<CodePointRange, $($merged.Count)> letter_ranges = {{")
foreach ($range in $merged) {
    $low = [Convert]::ToString([uint32]$range.Low, 16).ToUpperInvariant()
    $high = [Convert]::ToString([uint32]$range.High, 16).ToUpperInvariant()
    $lines.Add("    CodePointRange{0x$low, 0x$high},")
}
$lines.Add('}};')
$lines.Add('')
$lines.Add('} // namespace ube::unicode')

$resolvedOutput = [System.IO.Path]::GetFullPath($OutputPath)
[System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($resolvedOutput)) | Out-Null
[System.IO.File]::WriteAllLines($resolvedOutput, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated $($merged.Count) Unicode letter ranges in $resolvedOutput"
