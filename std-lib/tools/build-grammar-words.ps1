$ErrorActionPreference = 'Stop'
# Extracts literal words, including contextual/rejected forms, without inventing keywords.
$repo = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$files = @('lang-doc/grammar/ube.ebnf','lang-doc/grammar/conditional-compilation.ebnf')
$words = @{}
foreach ($file in $files) {
    $text = Get-Content (Join-Path $repo $file) -Raw
    $text = [regex]::Replace($text, '\(\*.*?\*\)', '', 'Singleline')
    foreach ($match in [regex]::Matches($text, '"([A-Za-z][A-Za-z0-9_ ]*)"')) {
        $word = $match.Groups[1].Value
        if (-not $words.ContainsKey($word)) { $words[$word] = @() }
        if ($file -notin $words[$word]) { $words[$word] += $file }
    }
}
$lines = @('# Grammar literal words', '', 'Generated by `std-lib/tools/build-grammar-words.ps1` from both normative EBNFs.', '',
'This is not a reserved-keyword list. Contextual words, metadata names and recognized-but-rejected syntax remain included. Library functions resolve as identifiers; see [language surface](LANGUAGE-SURFACE.md).', '',
'| Literal | Grammar |','|---|---|')
foreach ($word in $words.Keys | Sort-Object) { $lines += '| `' + $word + '` | ' + ($words[$word] -join ', ') + ' |' }
$lines += @('', "Total: $($words.Count) distinct alphabetic literals.")
$lines | Set-Content (Join-Path $repo 'compiler/GRAMMAR-WORDS.md') -Encoding UTF8
Write-Output "PASS: extracted $($words.Count) distinct alphabetic literals from both normative grammars."
