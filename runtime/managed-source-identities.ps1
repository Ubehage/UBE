# Generates/verifies compiled accidental-corruption checks for the reviewed support sources.
param([switch]$Write)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$encoding = New-Object Text.UTF8Encoding($false, $true)
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$entries = @([IO.File]::ReadAllLines((Join-Path $PSScriptRoot 'managed-support-sources.txt'), $encoding) | ForEach-Object { $_.Trim() } | Where-Object { $_ -and -not $_.StartsWith('#') })
$records = @()
foreach ($entry in $entries) {
    if ($entry -notmatch '^std-lib/src/portable/[A-Za-z_][A-Za-z0-9_]*\.bas$') { throw "Invalid support identity source: $entry" }
    $bytes = [IO.File]::ReadAllBytes((Join-Path $root $entry))
    $low = 1
    $high = 0
    $length = 0
    for ($i=0; $i -lt $bytes.Length; $i++) {
        if ($bytes[$i] -eq 13 -and $i+1 -lt $bytes.Length -and $bytes[$i+1] -eq 10) { continue }
        $low = ($low + $bytes[$i]) % 65521
        $high = ($high + $low) % 65521
        $length++
    }
    $records += [pscustomobject]@{Length=$length;Low=$low;High=$high}
}
$lines = @('UBE SOURCE 1 MODULE','Attribute UBE_Name = "ManagedSourceAssets"',"' Generated by runtime/managed-source-identities.ps1 from the reviewed source ledger.","' Canonical CRLF/LF length and two-sum checksum detect accidental corruption, not hostile replacement.",('Public Const SourceCount As Long = '+$records.Count),'')
foreach ($field in @('Length','Low','High')) {
    $lines += 'Private Function Expected'+$field+'(ByVal Index As Long) As Long'
    $lines += '    Expected'+$field+' = -1'
    for ($i=0; $i -lt $records.Count; $i++) { $lines += '    If Index = '+$i+' Then Expected'+$field+' = '+$records[$i].$field }
    $lines += @('End Function','')
}
$lines += @'
' Checks the same owned bytes subsequently parsed, so replacement cannot occur between check and use.
Public Function Validate(ByRef Bytes() As Byte, ByVal Identity As Long) As Boolean
    Validate = ValidateSpan(Bytes, 0, BufferPrimitives.ByteStorageLength(Bytes), Identity)
End Function

Public Function ValidateSpan(ByRef Bytes() As Byte, ByVal Start As Long, ByVal Count As Long, ByVal Identity As Long) As Boolean
    Dim Index As Long
    Dim Size As Long
    Dim Length As Long
    Dim Low As Long = 1
    Dim High As Long
    Dim Included As Boolean
    Dim Finish As Long
    If Identity < 0 Or Identity >= SourceCount Then Exit Function
    Size = BufferPrimitives.ByteStorageLength(Bytes)
    If Start < 0 Or Count < 0 Or Start > Size Then Exit Function
    If Count > Size - Start Then Exit Function
    Index = Start
    Finish = Start + Count
    Do While Index < Finish
        Included = True
        If Bytes(Index) = 13 And Index + 1 < Finish Then
            If Bytes(Index + 1) = 10 Then Included = False
        End If
        If Included Then
            Low = (Low + Bytes(Index)) Mod 65521
            High = (High + Low) Mod 65521
            Length = Length + 1
        End If
        Index = Index + 1
    Loop
    ValidateSpan = Length = ExpectedLength(Identity) And Low = ExpectedLow(Identity) And High = ExpectedHigh(Identity)
End Function

Private Intrinsic Function ModuleLength(ByRef Values() As ProjectSyntax.ParsedModule) As Long
Attribute ModuleLength.UBE_Primitive = "Array.Length"
End Function

' Checks private source provenance even when a caller supplies already parsed arenas.
Public Function ValidateProject(ByRef Bytes() As Byte, ByRef Modules() As ProjectSyntax.ParsedModule, ByRef Counts As ProjectSyntax.ProjectCounts, ByRef BadModule As Long) As Boolean
    Dim Index As Long
    Dim Identity As Long
    BadModule = -1
    If Counts.ModuleCount < 0 Or Counts.ModuleCount > ModuleLength(Modules) Or Counts.ModuleCount > 128 Then Exit Function
    If Counts.ByteCount < 0 Or Counts.ByteCount > BufferPrimitives.ByteStorageLength(Bytes) Then Exit Function
    Do While Index < Counts.ModuleCount
        If Modules(Index).LookupDomain < 0 Or Modules(Index).LookupDomain > 1 Then BadModule = Index: Exit Function
        If Modules(Index).LookupDomain = 1 Then
            BadModule = Index
            If Modules(Index).ByteBase < 0 Or Modules(Index).ByteBase > Counts.ByteCount Then Exit Function
            If Modules(Index).ByteCount < 0 Or Modules(Index).ByteCount > Counts.ByteCount - Modules(Index).ByteBase Then Exit Function
            If Not ValidateSpan(Bytes, Modules(Index).ByteBase, Modules(Index).ByteCount, Identity) Then Exit Function
            Identity = Identity + 1
        End If
        Index = Index + 1
    Loop
    If Identity <> 0 And Identity <> SourceCount Then Exit Function
    BadModule = -1
    ValidateProject = True
End Function
'@ -split '\r?\n'
$expected = ($lines -join "`r`n") + "`r`n"
$path = Join-Path $root 'compiler/src/ManagedSourceAssets.bas'
if ($Write) { [IO.File]::WriteAllText($path, $expected, $encoding) }
if (-not [IO.File]::Exists($path) -or [IO.File]::ReadAllText($path, $encoding).Replace("`r`n","`n") -cne $expected.Replace("`r`n","`n")) {
    throw 'Managed source identities differ from reviewed sources; run -Write after reviewing changes'
}
Write-Output "PASS managed support source identities: $($records.Count) ordered sources"
